const { test, expect } = require('@playwright/test');
const path = require('path');
const url = 'file://' + path.resolve(__dirname, '../atelier.html');
test('bibliothèque, persistance, sélection et variantes A/B', async ({ page }) => {
  const errors=[];page.on('pageerror', e=>errors.push(e.message));
  await page.goto(url);
  await expect(page.locator('#status')).toContainText('Stockage local prêt');
  await page.locator('#chapter').fill('Thalès');
  await page.locator('#name').fill('Triangles emboîtés');
  await page.locator('#statement').fill('Calculer MN avec Thalès.');
  await page.locator('#answer').fill('MN = 5 cm.');
  await page.locator('#statementB').fill('Calculer PQ avec Thalès.');
  await page.locator('#answerB').fill('PQ = 4,8 cm.');
  await page.locator('#points').fill('20');
  await page.getByRole('button',{name:'Enregistrer la ressource'}).click();
  await expect(page.locator('#items')).toContainText('Triangles emboîtés');
  await page.reload();
  await expect(page.locator('#items')).toContainText('Triangles emboîtés');
  await page.getByLabel('Inclure dans le contrôle').check();
  await expect(page.locator('#selection')).toContainText('20 / 20');
  await page.locator('#versions').selectOption('AB');
  await page.evaluate(()=>{window.print=()=>{}});
  await page.locator('#print').click();
  await expect(page.locator('#paper .page')).toHaveCount(4);
  await expect(page.locator('#paper .page').nth(0)).toContainText('Calculer MN');
  await expect(page.locator('#paper .page').nth(1)).toContainText('Calculer PQ');
  await expect(page.locator('#paper .page').nth(2)).toContainText('MN = 5');
  await expect(page.locator('#paper .page').nth(3)).toContainText('PQ = 4,8');
  expect(errors).toEqual([]);
});
test('une variante B manquante bloque l’impression',async({page})=>{
  await page.goto(url);
  await page.locator('#chapter').fill('Calcul littéral');
  await page.locator('#name').fill('Développer');
  await page.locator('#statement').fill('Développer 2(x+3)');
  await page.locator('#points').fill('20');
  await page.getByRole('button',{name:'Enregistrer la ressource'}).click();
  await page.getByLabel('Inclure dans le contrôle').check();
  await page.locator('#versions').selectOption('AB');
  page.once('dialog',dialog=>dialog.accept());
  await page.locator('#print').click();
  await expect(page.locator('#paper .page')).toHaveCount(0);
});
